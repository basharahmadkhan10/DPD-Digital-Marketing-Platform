using System.Net;
using System.Text;
using System.Text.RegularExpressions;

namespace DPDDigitalMarketing.Services
{
    public static class PdfDocumentBuilder
    {
        private const int PageWidth = 595;
        private const int PageHeight = 842;
        private const int MarginLeft = 50;
        private const int MaxCharsPerLine = 82;

        private sealed record PdfLine(string Text, bool IsHeading, bool IsSubtle);

        public static byte[] BuildIssuePdf(DigitalIssue issue, string? licensedToEmail)
        {
            var lines = new List<PdfLine>
            {
                new("PUBLICATIONS DIVISION (DPD)", true, false),
                new("Ministry of Information & Broadcasting, Government of India", false, true),
                new(new string('-', 78), false, true),
                new(SanitizeText(issue.Title), true, false),
                new($"Issue: {SanitizeText(issue.IssueNumber)}  |  Category: {SanitizeText(issue.Category)}  |  Language: {SanitizeText(issue.Language)}", false, true),
                new($"Release Date: {issue.ReleaseDate:dd MMM yyyy}  |  Licensed To: {SanitizeText(string.IsNullOrWhiteSpace(licensedToEmail) ? "Official DPD Reader" : licensedToEmail)}", false, true),
                new(new string('=', 78), false, true),
                new("", false, false)
            };

            int secNum = 1;
            foreach (var section in issue.Sections)
            {
                lines.Add(new PdfLine($"{secNum}. {SanitizeText(section.Title)} ({SanitizeText(section.Duration)})", true, false));
                lines.Add(new PdfLine(new string('-', 50), false, true));

                var plain = HtmlToPlainText(section.HtmlContent);
                foreach (var para in plain.Split('\n'))
                {
                    var trimmed = para.Trim();
                    if (string.IsNullOrEmpty(trimmed))
                    {
                        lines.Add(new PdfLine("", false, false));
                        continue;
                    }

                    foreach (var wrapped in WrapText(trimmed, MaxCharsPerLine))
                    {
                        lines.Add(new PdfLine(wrapped, false, false));
                    }
                }

                lines.Add(new PdfLine("", false, false));
                secNum++;
            }

            lines.Add(new PdfLine(new string('-', 78), false, true));
            lines.Add(new PdfLine("Official Digital Edition generated by DPD Digital Marketing Platform.", false, true));

            var pages = PaginateLines(lines, 44);
            return RenderPdfBytes(pages);
        }

        public static byte[] BuildOrderReceiptPdf(Models.Order order)
        {
            var lines = new List<PdfLine>
            {
                new("PUBLICATIONS DIVISION (DPD)", true, false),
                new("Ministry of Information & Broadcasting, Government of India", false, true),
                new(new string('=', 78), false, true),
                new($"OFFICIAL ORDER RECEIPT  -  #DPD-{order.Id}", true, false),
                new(new string('-', 78), false, true),
                new($"Customer Name  : {SanitizeText(order.CustomerName)}", false, false),
                new($"Customer Email : {SanitizeText(order.CustomerEmail)}", false, false),
                new($"Order Date     : {order.OrderDate:dd MMM yyyy, hh:mm tt} UTC", false, false),
                new($"Sale Channel   : {SanitizeText(order.SaleChannel)}", false, false),
                new($"Order Status   : {SanitizeText(order.Status)}", false, false),
                new(new string('-', 78), false, true),
                new("", false, false),
                new("PURCHASED PUBLICATIONS:", true, false),
                new(new string('-', 50), false, true)
            };

            int idx = 1;
            foreach (var item in order.OrderItems)
            {
                var title = SanitizeText(item.Product?.Title ?? $"Publication #{item.ProductId}");
                foreach (var wrapped in WrapText($"{idx}. {title}", 64))
                {
                    lines.Add(new PdfLine(wrapped, false, false));
                }
                lines.Add(new PdfLine($"    Qty: {item.Quantity}   |   Unit Price: Rs.{item.UnitPrice:0.00}   |   Subtotal: Rs.{(item.Quantity * item.UnitPrice):0.00}", false, true));
                idx++;
            }

            lines.Add(new PdfLine("", false, false));
            lines.Add(new PdfLine(new string('=', 78), false, true));
            lines.Add(new PdfLine($"TOTAL PAID : Rs.{order.TotalAmount:0.00}", true, false));
            lines.Add(new PdfLine(new string('=', 78), false, true));
            lines.Add(new PdfLine("", false, false));
            lines.Add(new PdfLine("Thank you for supporting Publications Division (Govt. of India).", false, true));

            var pages = PaginateLines(lines, 44);
            return RenderPdfBytes(pages);
        }

        private static List<List<PdfLine>> PaginateLines(List<PdfLine> allLines, int linesPerPage)
        {
            var pages = new List<List<PdfLine>>();
            for (int i = 0; i < allLines.Count; i += linesPerPage)
            {
                pages.Add(allLines.GetRange(i, Math.Min(linesPerPage, allLines.Count - i)));
            }
            if (pages.Count == 0)
            {
                pages.Add(new List<PdfLine> { new("Empty Publication", true, false) });
            }
            return pages;
        }

        private static byte[] RenderPdfBytes(List<List<PdfLine>> pages)
        {
            using var ms = new MemoryStream();
            var offsets = new List<long> { 0 };

            void WriteAscii(string s)
            {
                var bytes = Encoding.ASCII.GetBytes(s);
                ms.Write(bytes, 0, bytes.Length);
            }

            void WriteLatin1(string s)
            {
                var bytes = Encoding.Latin1.GetBytes(s);
                ms.Write(bytes, 0, bytes.Length);
            }

            WriteAscii("%PDF-1.4\n");

            // Object 1: Catalog, Object 2: Pages, Object 3: Helvetica, Object 4: Helvetica-Bold
            int pageCount = pages.Count;
            int firstPageObjId = 5;

            // Obj 1: Catalog
            offsets.Add(ms.Position);
            WriteAscii("1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n");

            // Obj 2: Pages
            var kids = string.Join(" ", Enumerable.Range(0, pageCount).Select(i => $"{firstPageObjId + i * 2} 0 R"));
            offsets.Add(ms.Position);
            WriteAscii($"2 0 obj\n<< /Type /Pages /Kids [ {kids} ] /Count {pageCount} >>\nendobj\n");

            // Obj 3: Regular Font
            offsets.Add(ms.Position);
            WriteAscii("3 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>\nendobj\n");

            // Obj 4: Bold Font
            offsets.Add(ms.Position);
            WriteAscii("4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>\nendobj\n");

            for (int p = 0; p < pageCount; p++)
            {
                int pageObjId = firstPageObjId + p * 2;
                int contentObjId = pageObjId + 1;

                var streamSb = new StringBuilder();
                streamSb.Append("BT\n");
                int y = PageHeight - 55;

                foreach (var line in pages[p])
                {
                    var fontRef = line.IsHeading ? "/F2" : "/F1";
                    var fontSize = line.IsHeading ? 12 : (line.IsSubtle ? 9 : 10);
                    var color = line.IsHeading ? "0.06 0.09 0.16 rg" : (line.IsSubtle ? "0.35 0.40 0.48 rg" : "0.10 0.12 0.16 rg");

                    streamSb.Append($"{fontRef} {fontSize} Tf {color} 1 0 0 1 {MarginLeft} {y} Tm ({EscapePdfText(line.Text)}) Tj\n");
                    y -= line.IsHeading ? 18 : 15;
                }

                // Footer page number
                streamSb.Append($"/F1 9 Tf 0.45 0.50 0.56 rg 1 0 0 1 {MarginLeft} 30 Tm (Publications Division - Digital Edition  |  Page {p + 1} of {pageCount}) Tj\n");
                streamSb.Append("ET\n");

                var streamContent = streamSb.ToString();
                var streamByteLen = Encoding.Latin1.GetByteCount(streamContent);

                // Page Object
                offsets.Add(ms.Position);
                WriteAscii($"{pageObjId} 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {PageWidth} {PageHeight}] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents {contentObjId} 0 R >>\nendobj\n");

                // Content Stream Object
                offsets.Add(ms.Position);
                WriteAscii($"{contentObjId} 0 obj\n<< /Length {streamByteLen} >>\nstream\n");
                WriteLatin1(streamContent);
                WriteAscii("\nendstream\nendobj\n");
            }

            long xrefPos = ms.Position;
            WriteAscii($"xref\n0 {offsets.Count}\n");
            WriteAscii("0000000000 65535 f \n");
            for (int i = 1; i < offsets.Count; i++)
            {
                WriteAscii($"{offsets[i]:D10} 00000 n \n");
            }

            WriteAscii($"trailer\n<< /Size {offsets.Count} /Root 1 0 R >>\nstartxref\n{xrefPos}\n%%EOF\n");
            return ms.ToArray();
        }

        private static string HtmlToPlainText(string html)
        {
            if (string.IsNullOrWhiteSpace(html)) return string.Empty;

            var text = Regex.Replace(html, @"<\s*(br|p|div|li|tr|h[1-6])\b[^>]*>", "\n", RegexOptions.IgnoreCase);
            text = Regex.Replace(text, @"</\s*(p|div|li|tr|h[1-6])\s*>", "\n", RegexOptions.IgnoreCase);
            text = Regex.Replace(text, @"<\s*td\b[^>]*>", "  |  ", RegexOptions.IgnoreCase);
            text = Regex.Replace(text, @"<[^>]+>", string.Empty);
            text = WebUtility.HtmlDecode(text);
            text = Regex.Replace(text, @"[ \t]+", " ");
            text = Regex.Replace(text, @"\n{3,}", "\n\n");
            return SanitizeText(text);
        }

        private static string SanitizeText(string input)
        {
            if (string.IsNullOrEmpty(input)) return string.Empty;
            var replaced = input
                .Replace("₹", "Rs.")
                .Replace("•", "-")
                .Replace("—", "-")
                .Replace("–", "-")
                .Replace("‘", "'")
                .Replace("’", "'")
                .Replace("“", "\"")
                .Replace("”", "\"");

            var sb = new StringBuilder(replaced.Length);
            foreach (char ch in replaced)
            {
                if (ch == '\n' || (ch >= 32 && ch <= 126))
                {
                    sb.Append(ch);
                }
            }
            return sb.ToString();
        }

        private static IEnumerable<string> WrapText(string text, int maxWidth)
        {
            if (text.Length <= maxWidth)
            {
                yield return text;
                yield break;
            }

            var words = text.Split(' ', StringSplitOptions.RemoveEmptyEntries);
            var current = new StringBuilder();
            foreach (var word in words)
            {
                if (current.Length > 0 && current.Length + word.Length + 1 > maxWidth)
                {
                    yield return current.ToString();
                    current.Clear();
                }

                if (current.Length > 0) current.Append(' ');
                current.Append(word);
            }

            if (current.Length > 0)
            {
                yield return current.ToString();
            }
        }

        private static string EscapePdfText(string input)
        {
            return input
                .Replace("\\", "\\\\")
                .Replace("(", "\\(")
                .Replace(")", "\\)");
        }
    }
